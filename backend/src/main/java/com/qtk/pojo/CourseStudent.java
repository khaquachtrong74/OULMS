package com.qtk.pojo;

import jakarta.persistence.Basic;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.NamedQueries;
import jakarta.persistence.NamedQuery;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;
import jakarta.persistence.Temporal;
import jakarta.persistence.TemporalType;
import jakarta.xml.bind.annotation.XmlRootElement;
import java.io.Serializable;
import java.util.Date;

/**
 *
 * @author ngodo
 */
@Entity
@Table(name = "course_student")
@XmlRootElement
@NamedQueries({
    @NamedQuery(name = "CourseStudent.findAll", query = "SELECT c FROM CourseStudent c"),
    @NamedQuery(name = "CourseStudent.findById", query = "SELECT c FROM CourseStudent c WHERE c.id = :id"),
    @NamedQuery(name = "CourseStudent.findByEnrolledAt", query = "SELECT c FROM CourseStudent c WHERE c.enrolledAt = :enrolledAt"),
    @NamedQuery(name = "CourseStudent.findByCreatedAt", query = "SELECT c FROM CourseStudent c WHERE c.createdAt = :createdAt"),
    @NamedQuery(name = "CourseStudent.findByUpdatedAt", query = "SELECT c FROM CourseStudent c WHERE c.updatedAt = :updatedAt")})
public class CourseStudent implements Serializable {

    private static final long serialVersionUID = 1L;
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Basic(optional = false)
    @Column(name = "id")
    private Integer id;
    @Column(name = "enrolled_at")
    @Temporal(TemporalType.TIMESTAMP)
    private Date enrolledAt;
    @Column(name = "created_at")
    @Temporal(TemporalType.TIMESTAMP)
    private Date createdAt;
    @Column(name = "updated_at")
    @Temporal(TemporalType.TIMESTAMP)
    private Date updatedAt;
    @JoinColumn(name = "course_id", referencedColumnName = "id")
    @OneToOne(optional = false)
    private Course courseId;
    @JoinColumn(name = "student_id", referencedColumnName = "id")
    @OneToOne(optional = false)
    private User studentId;

    public CourseStudent() {
    }

    public CourseStudent(Integer id) {
        this.id = id;
    }

    public Integer getId() {
        return id;
    }

    public void setId(Integer id) {
        this.id = id;
    }

    public Date getEnrolledAt() {
        return enrolledAt;
    }

    public void setEnrolledAt(Date enrolledAt) {
        this.enrolledAt = enrolledAt;
    }

    public Date getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Date createdAt) {
        this.createdAt = createdAt;
    }

    public Date getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Date updatedAt) {
        this.updatedAt = updatedAt;
    }

    public Course getCourseId() {
        return courseId;
    }

    public void setCourseId(Course courseId) {
        this.courseId = courseId;
    }

    public User getStudentId() {
        return studentId;
    }

    public void setStudentId(User studentId) {
        this.studentId = studentId;
    }

    @Override
    public int hashCode() {
        int hash = 0;
        hash += (id != null ? id.hashCode() : 0);
        return hash;
    }

    @Override
    public boolean equals(Object object) {
        // TODO: Warning - this method won't work in the case the id fields are not set
        if (!(object instanceof CourseStudent)) {
            return false;
        }
        CourseStudent other = (CourseStudent) object;
        if ((this.id == null && other.id != null) || (this.id != null && !this.id.equals(other.id))) {
            return false;
        }
        return true;
    }

    @Override
    public String toString() {
        return "com.qtk.pojo.CourseStudent[ id=" + id + " ]";
    }
    
}
